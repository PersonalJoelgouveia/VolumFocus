import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import { readFileSync } from 'fs';
import { doc, getDoc, setDoc, serverTimestamp, writeBatch } from 'firebase/firestore';
const env = await initializeTestEnvironment({ projectId:'demo-vf', firestore:{ rules: readFileSync('firestore.etapaA.rules','utf8'), host:'127.0.0.1', port:8080 }});
const PT='joelgouveia16@gmail.com', AL='aluno@x.com', AL2='outro@x.com', EST='estranho@x.com';
const ctx=(uid,email)=>env.authenticatedContext(uid,{email,email_verified:true}).firestore();
let ok=0,bad=0;
const t=async(n,p)=>{try{await p;ok++;console.log('OK  ',n)}catch(e){bad++;console.log('FAIL',n,String(e.message).slice(0,120))}};
await env.withSecurityRulesDisabled(async c=>{const d=c.firestore();
  await setDoc(doc(d,'alunos',AL),{email:AL});await setDoc(doc(d,'alunos',AL2),{email:AL2});});
const pt=ctx('pt1',PT), al=ctx('a1',AL), est=ctx('e1',EST);
await t('PT le aluno',assertSucceeds(getDoc(doc(pt,'alunos',AL))));
await t('aluno le proprio',assertSucceeds(getDoc(doc(al,'alunos',AL))));
await t('aluno NAO le outro',assertFails(getDoc(doc(al,'alunos',AL2))));
await t('estranho NAO le aluno',assertFails(getDoc(doc(est,'alunos',AL))));
await t('aluno NAO escreve alunos',assertFails(setDoc(doc(al,'alunos',AL),{x:1})));
await t('PT escreve alunos c/ ownerUUID',assertSucceeds(setDoc(doc(pt,'alunos',AL),{email:AL,ownerUUID:'x'},{merge:true})));
await t('aluno NAO le anotacoes',assertFails(getDoc(doc(al,'alunos',AL,'anotacoes','n1'))));
await t('PT escreve anotacao',assertSucceeds(setDoc(doc(pt,'alunos',AL,'anotacoes','n1'),{a:1})));
await t('aluno le rotinas proprias',assertSucceeds(getDoc(doc(al,'alunos',AL,'rotinas','r1'))));
await t('aluno NAO escreve rotina',assertFails(setDoc(doc(al,'alunos',AL,'rotinas','r1'),{a:1})));
const onl=(id)=>({id,alunoId:'loc1',date:'2026-10-09',protocol:'online',anthropometry:{peso:70,altura:170,imc:24.2},circumferences:[],skinfolds:{},results:{relacaoCinturaQuadril:0.8},createdAt:'a',updatedAt:'a',status:'enviada',submittedBy:'aluno'});
await t('aluno cria avaliacao online propria',assertSucceeds(setDoc(doc(al,'alunos',AL,'avaliacoesFisicas','o1'),onl('o1'))));
await t('aluno NAO cria em outro aluno',assertFails(setDoc(doc(al,'alunos',AL2,'avaliacoesFisicas','o2'),onl('o2'))));
await t('aluno NAO cria avaliacao nao-online',assertFails(setDoc(doc(al,'alunos',AL,'avaliacoesFisicas','o3'),{...onl('o3'),protocol:'dobras'})));
await t('aluno NAO atualiza avaliacao',assertFails(setDoc(doc(al,'alunos',AL,'avaliacoesFisicas','o1'),{...onl('o1'),notes:'x'})));
await t('PT cria avaliacao dobras',assertSucceeds(setDoc(doc(pt,'alunos',AL,'avaliacoesFisicas','p1'),{id:'p1',protocol:'dobras'})));
await t('aluno escreve cargas proprias',assertSucceeds(setDoc(doc(al,'alunos',AL,'cargas','atuais'),{cargas:{}})));
await t('aluno NAO escreve cargas de outro',assertFails(setDoc(doc(al,'alunos',AL2,'cargas','atuais'),{cargas:{}})));
await t('PT escreve cargas',assertSucceeds(setDoc(doc(pt,'alunos',AL,'cargas','atuais'),{cargas:{}})));
await t('backup proprio aluno',assertSucceeds(setDoc(doc(al,'backups',AL),{v:2})));
await t('backup estranho NEGADO',assertFails(setDoc(doc(est,'backups',EST),{v:2})));
await t('backup PT',assertSucceeds(setDoc(doc(pt,'backups',PT),{v:2})));
await t('backup de outro NEGADO',assertFails(setDoc(doc(al,'backups',AL2),{v:2})));
const n=(id,email,over={})=>({id,alunoEmail:email,alunoNome:'A',dia:1,dataTreino:'2026-10-09',lida:false,criadaEm:'t',ownerUUID:'u',...over});
await t('aluno cria notificacao valida',assertSucceeds(setDoc(doc(al,'notificacoesTreinos','n1'),n('n1',AL))));
await t('estranho NAO cria notificacao',assertFails(setDoc(doc(est,'notificacoesTreinos','n2'),n('n2',EST))));
await t('aluno NAO forja alunoEmail',assertFails(setDoc(doc(al,'notificacoesTreinos','n3'),n('n3',AL2))));
await t('notificacao com campo extra NEGADA',assertFails(setDoc(doc(al,'notificacoesTreinos','n4'),n('n4',AL,{x:1}))));
await t('notificacao id != doc NEGADA',assertFails(setDoc(doc(al,'notificacoesTreinos','n5'),n('zz',AL))));
await t('aluno NAO le notificacao',assertFails(getDoc(doc(al,'notificacoesTreinos','n1'))));
await t('PT le notificacao',assertSucceeds(getDoc(doc(pt,'notificacoesTreinos','n1'))));
// ownerUUID (transacao/batch: vinculo + indice)
const U='123e4567-e89b-42d3-a456-426614174000';
const link=async(c,uid,u)=>{const b=writeBatch(c);b.set(doc(c,'userOwners',uid),{ownerUUID:u,createdAt:serverTimestamp()});b.set(doc(c,'ownerUUIDs',u),{uid,createdAt:serverTimestamp()});return b.commit();};
await t('PT cria vinculo ownerUUID',assertSucceeds(link(pt,'pt1',U)));
await t('aluno cadastrado cria vinculo',assertSucceeds(link(al,'a1','223e4567-e89b-42d3-a456-426614174001')));
await t('estranho NAO cria vinculo',assertFails(link(est,'e1','323e4567-e89b-42d3-a456-426614174002')));
await t('vinculo imutavel',assertFails(setDoc(doc(pt,'userOwners','pt1'),{ownerUUID:'423e4567-e89b-42d3-a456-426614174003',createdAt:serverTimestamp()})));
await t('le o proprio vinculo',assertSucceeds(getDoc(doc(pt,'userOwners','pt1'))));
await t('NAO le vinculo alheio',assertFails(getDoc(doc(al,'userOwners','pt1'))));
await t('colecao desconhecida NEGADA',assertFails(setDoc(doc(pt,'qualquer','x'),{a:1})));
console.log(`\n${ok} ok, ${bad} falhas`);
await env.cleanup();
